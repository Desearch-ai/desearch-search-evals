def build_queries(
    domains: list[str] | None = None,
    include_accounts: bool = True,
    include_topics: bool = True,
) -> list[dict]:
    """Return harvest queries: {label, query, kind}. kind in {account, topic}."""
    out: list[dict] = []

    if include_accounts:
        for domain, handles in ACCOUNTS.items():
            if domains and domain not in domains:
                continue
            for h in dict.fromkeys(handles):
                out.append(
                    {"label": f"{domain}:@{h}", "query": f"from:{h}", "kind": "account"}
                )

    if include_topics:
        for domain, frags in TOPICS.items():
            if domains and domain not in domains:
                continue
            for frag in frags:
                out.append(
                    {"label": f"{domain}:{frag[:24]}", "query": frag, "kind": "topic"}
                )

    return out
